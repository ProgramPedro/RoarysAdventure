inline constexpr int kGlyphCount =
    static_cast<int>(sizeof(kGlyphs) / sizeof(kGlyphs[0]));

inline const Glyph* find(char c) {
    for (int i = 0; i < kGlyphCount; ++i) {
        if (kGlyphs[i].character == c) {
            return &kGlyphs[i];
        }
    }
    return nullptr;
}

